package dev.mytvhome.home;

import android.content.Context;
import android.content.Intent;
import android.graphics.Bitmap;
import android.graphics.BitmapFactory;
import android.net.Uri;
import android.os.Handler;
import android.os.Looper;
import android.util.Log;
import android.util.LruCache;
import android.widget.ImageView;

import org.json.JSONArray;
import org.json.JSONObject;

import java.io.InputStream;
import java.net.HttpURLConnection;
import java.net.URL;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Live TV channels (assets/live/channels.json, generated by tools/build_live_list.py):
 *  - "youtube": official 24/7 YouTube live stream; the current live video is looked up when chosen,
 *  - "stream":  free public stream (iptv-org), played in PlayerActivity,
 *  - "app":     channel only offered in an official app on this TV (opened).
 */
final class LiveTv {
    static final String[] TABS = {"News", "Entertainment", "Religious", "Kids", "Sports & Music"};

    static final class Channel {
        final String name, type, category, logo, url, channelId, pkg;
        final Map<String, String> headers = new HashMap<>();
        Channel(JSONObject o) {
            name = o.optString("name");
            type = o.optString("type");
            category = o.optString("category", "Entertainment");
            logo = o.isNull("logo") ? null : o.optString("logo", null);
            url = o.optString("url", null);
            channelId = o.optString("channel_id", null);
            pkg = o.optString("package", null);
            JSONObject h = o.optJSONObject("headers");
            if (h != null) for (java.util.Iterator<String> k = h.keys(); k.hasNext(); ) {
                String key = k.next();
                headers.put(key, h.optString(key));
            }
        }
    }

    interface Done { void run(String error); }

    private final Context ctx;
    private final Handler main = new Handler(Looper.getMainLooper());
    private final ExecutorService io = Executors.newFixedThreadPool(3);
    private final LruCache<String, Bitmap> logos = new LruCache<>(80);
    final List<Channel> all = new ArrayList<>();

    LiveTv(Context c) {
        ctx = c.getApplicationContext();
        try (InputStream in = ctx.getAssets().open("live/channels.json")) {
            JSONArray arr = new JSONObject(Assistant.read(in)).getJSONArray("channels");
            for (int i = 0; i < arr.length(); i++) all.add(new Channel(arr.getJSONObject(i)));
        } catch (Exception e) {
            Log.e("MyHome", "channels.json", e);
        }
    }

    List<Channel> inTab(String tab) {
        List<Channel> out = new ArrayList<>();
        for (Channel c : all) if (c.category.equals(tab)) out.add(c);
        return out;
    }

    /** Streams of the same tab, in order: the zapping list for PlayerActivity. */
    ArrayList<String> streamNames(String tab) {
        ArrayList<String> out = new ArrayList<>();
        for (Channel c : inTab(tab)) if ("stream".equals(c.type)) out.add(c.name);
        return out;
    }

    Channel find(String name) {
        if (name == null) return null;
        String n = name.toLowerCase(Locale.US).replaceAll("[^a-z0-9]", "");
        Channel loose = null;
        for (Channel c : all) {
            String cn = c.name.toLowerCase(Locale.US).replaceAll("[^a-z0-9]", "");
            if (cn.equals(n)) return c;
            if (loose == null && (cn.startsWith(n) || n.startsWith(cn) || cn.contains(n))) loose = c;
        }
        return loose;
    }

    Set<String> names() {
        Set<String> s = new LinkedHashSet<>();
        for (Channel c : all) s.add(c.name);
        return s;
    }

    /** Start watching a channel. Errors (e.g. YouTube channel not live) come back on the main thread. */
    void play(final Channel c, final String tab, final Done done) {
        switch (c.type) {
            case "stream":
                ctx.startActivity(new Intent(ctx, PlayerActivity.class).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
                        .putExtra("name", c.name).putExtra("tab", tab != null ? tab : c.category));
                done.run(null);
                break;
            case "app": {
                Intent i = ctx.getPackageManager().getLeanbackLaunchIntentForPackage(c.pkg);
                if (i == null) { done.run(c.name + " needs its app, which isn't installed."); return; }
                ctx.startActivity(i.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK));
                done.run(null);
                break;
            }
            case "youtube":
                io.execute(() -> {
                    String id = currentLiveVideo(c.channelId);
                    main.post(() -> {
                        if (id == null) { done.run(c.name + " isn't live on YouTube right now."); return; }
                        // NEW_TASK|CLEAR_TASK: otherwise YouTube can stay in whatever screen it was on.
                        ctx.startActivity(new Intent(Intent.ACTION_VIEW, Uri.parse("https://www.youtube.com/watch?v=" + id))
                                .setPackage("com.google.android.youtube.tv")
                                .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK | Intent.FLAG_ACTIVITY_CLEAR_TASK));
                        done.run(null);
                    });
                });
                break;
            default:
                done.run("Unknown channel type");
        }
    }

    /** The channel's current live video id, read from the canonical link near the top of its /live page. */
    private static String currentLiveVideo(String channelId) {
        if (channelId == null) return null;
        try {
            HttpURLConnection c = (HttpURLConnection) new URL("https://www.youtube.com/channel/" + channelId + "/live").openConnection();
            c.setRequestProperty("User-Agent", "Mozilla/5.0 (Linux; Android 11) AppleWebKit/537.36 Chrome/139 Safari/537.36");
            c.setRequestProperty("Cookie", "CONSENT=YES+1");
            c.setConnectTimeout(8000);
            c.setReadTimeout(8000);
            Pattern p = Pattern.compile("<link rel=\"canonical\" href=\"https://www\\.youtube\\.com/watch\\?v=([\\w-]{11})\"");
            StringBuilder sb = new StringBuilder();
            try (InputStream in = c.getInputStream()) {
                byte[] buf = new byte[16384];
                for (int n; (n = in.read(buf)) > 0 && sb.length() < 600_000; ) {
                    sb.append(new String(buf, 0, n, "UTF-8"));
                    Matcher m = p.matcher(sb);
                    if (m.find()) return m.group(1);
                    if (sb.indexOf("</head>") >= 0) break;     // canonical is in <head>; not live
                }
            }
        } catch (Exception e) {
            Log.w("MyHome", "live id " + channelId, e);
        }
        return null;
    }

    void loadLogo(final String url, final ImageView into) {
        if (url == null) return;
        Bitmap cached = logos.get(url);
        if (cached != null) { into.setImageBitmap(cached); return; }
        into.setTag(url);
        io.execute(() -> {
            try {
                HttpURLConnection c = (HttpURLConnection) new URL(url).openConnection();
                c.setRequestProperty("User-Agent", "my-tv-home/1.0");
                c.setConnectTimeout(6000);
                c.setReadTimeout(6000);
                BitmapFactory.Options o = new BitmapFactory.Options();
                o.inPreferredConfig = Bitmap.Config.ARGB_8888;
                final Bitmap b;
                try (InputStream in = c.getInputStream()) { b = BitmapFactory.decodeStream(in, null, o); }
                if (b == null) return;
                final Bitmap small = b.getWidth() > 320 ? Bitmap.createScaledBitmap(b, 320, Math.max(1, 320 * b.getHeight() / b.getWidth()), true) : b;
                logos.put(url, small);
                main.post(() -> { if (url.equals(into.getTag())) into.setImageBitmap(small); });
            } catch (Exception ignored) {
                // no logo: the name card stays
            }
        });
    }
}
